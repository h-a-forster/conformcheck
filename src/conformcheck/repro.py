@dataclass
class Repro:
    title: str
    path: Path
    row: str
    kind: str
    exit_code: int | None = None


def _snippet(cell: Cell) -> str | None:
    row, lib, method, variant = cell.row, cell.library, cell.method, cell.variant
    if lib == "reference" and method == "split_abs":
        return REFERENCE_SNIPPET.format(mutant=variant)
    if row in SNIPPETS:
        return SNIPPETS[row]
    if method in ("cv_plus", "jackknife_plus") and f"{lib}/cv_plus" in SNIPPETS:
        return SNIPPETS[f"{lib}/cv_plus"]
    if cell.dgp not in ("cls_gauss",):
        return None
    if lib == "mapie":
        ill = None
        if variant.startswith("include_last_label="):
            v = variant.split("=", 1)[1]
            ill = {"True": True, "False": False}.get(v, v)
        return SNIPPETS["mapie/classifier"].format(score=method, ill=ill)
    if lib == "crepes":
        return SNIPPETS["crepes/classifier"].format(
            smoothing=variant == "smoothed", class_cond=method == "class_conditional"
        )
    if lib == "puncc":
        kind = "classwise_lac" if method == "class_conditional" else method
        return SNIPPETS["puncc/classifier"].format(kind=kind, rand=variant == "rand=True")
    if lib == "torchcp":
        kind = "lac" if method in ("lac", "class_conditional") else method
        return SNIPPETS["torchcp/classifier"].format(
            kind=kind, rand=variant == "randomized=True", class_cond=method == "class_conditional"
        )
    return None


def _mechanism(cell: Cell) -> str:
    if cell.status in ("ERROR", "OVER_REFUSED"):
        return "raises"
    if (
        cell.method == "split_abs"
        and cell.dgp in ("reg_gauss", "reg_hetero_t")
        and any(float(k) != 0 for k in cell.rank_offsets)
    ):
        return "rank"
    if (
        cell.method in ("cv_plus", "jackknife_plus")
        and cell.dgp == "reg_constant"
        and any(o != "0|0" for o in cell.rank_pairs)
    ):
        return "rank"
    return "coverage"


def _script(cell: Cell, kind: str, snippet: str) -> str:
    lib_name = cell.library if cell.library != "reference" else "numpy"
    head = PRELUDE.format(lib=lib_name)
    if cell.library == "torchcp":
        head += TORCHCP_STUBS
    body = head + MODELS + snippet
    is_cls = cell.dgp == "cls_gauss"
    model = "FixedClassifier()" if is_cls else "FixedRegressor()"
    alpha = cell.alpha
    if kind == "rank":
        if cell.method in ("cv_plus", "jackknife_plus"):
            nf = cell.n if cell.method == "jackknife_plus" else cell.n_folds
            return body + CROSS_RANK_HARNESS.format(n=cell.n, alpha=alpha, folds=nf)
        return body + RANK_HARNESS.format(n=cell.n, alpha=alpha)
    if kind.startswith("raises"):
        if cell.method in ("cv_plus", "jackknife_plus"):
            nf = cell.n if cell.method == "jackknife_plus" else cell.n_folds
            call = (
                f"        x, y = reg_data(rng, N)\n        x_test, _ = reg_data(rng, 3)\n"
                f"        intervals_cross(x, y, x_test, ALPHA, seed, {nf})"
            )
        elif is_cls:
            per = cell.method == "class_conditional"
            nn = "4 * N" if per else "N"
            call = (
                f"        x_cal, y_cal = cls_data(rng, {nn}, per_class={per})\n"
                f"        x_test, _ = cls_data(rng, 8)\n"
                f"        sets(x_cal, y_cal, x_test, ALPHA, seed)"
            )
        else:
            call = (
                "        x_cal, y_cal = reg_data(rng, N)\n"
                "        x_test, _ = reg_data(rng, 3)\n"
                "        intervals(x_cal, y_cal, x_test, ALPHA)"
            )
        return body + RAISES_HARNESS.format(model=model, n=cell.n, alpha=alpha, call=call)
    # coverage
    reps = 400
    m = 200
    if is_cls:
        per = cell.method == "class_conditional"
        nn = "4 * N" if per else "N"
        draw = (
            f"        x_cal, y_cal = cls_data(rng, {nn}, per_class=PER_CLASS)\n"
            f"        x_test, y_test = cls_data(rng, M, per_class=PER_CLASS)\n"
            f"        covered = sets(x_cal, y_cal, x_test, ALPHA, rep)[np.arange(M), y_test]"
        )
    elif cell.method in ("cv_plus", "jackknife_plus"):
        nf = cell.n if cell.method == "jackknife_plus" else cell.n_folds
        draw = (
            f"        x, y = reg_data(rng, N)\n        x_test, y_test = reg_data(rng, M)\n"
            f"        iv = intervals_cross(x, y, x_test, ALPHA, rep, {nf})\n"
            f"        covered = (iv[:, 0] <= y_test) & (y_test <= iv[:, 1])"
        )
    else:
        draw = (
            "        x_cal, y_cal = reg_data(rng, N)\n        x_test, y_test = reg_data(rng, M)\n"
            "        iv = intervals(x_cal, y_cal, x_test, ALPHA)\n"
            "        covered = (iv[:, 0] <= y_test) & (y_test <= iv[:, 1])"
        )
    exact = cell.law_kind == "exact" and not cell.one_sided
    return body + COVERAGE_HARNESS.format(
        model=model,
        n=cell.n,
        alpha=alpha,
        reps=reps,
        m=m,
        target=cell.target,
        exact=exact,
        per_class=cell.method == "class_conditional",
        draw=draw,
    )


def _raise_kind(c: Cell) -> str:
    msg = c.message.split(":", 1)
    return (msg[0] + ":" + msg[1][:40]) if len(msg) == 2 else c.message[:50]


def clusters(cells: list[Cell], include_controls: bool = True) -> list[tuple[Cell, str]]:
    """One representative cell per (row, mechanism) among non-PASS cells; raises are
    split further by exception message (``raises``, ``raises-2``, ...)."""
    synthetic = ("reg_gauss", "cls_gauss", "reg_constant")

    def rank(c: Cell) -> tuple:  # type: ignore[type-arg]
        a = Fraction(c.alpha)
        edge = a in (Fraction(1, c.n + 1), Fraction(9, 10 * (c.n + 1)))
        # synthetic DGPs first (the scripts rebuild those), then base alphas, then small n
        return (c.dgp not in synthetic, edge, c.n, -a)

    best: dict[tuple[str, str, str], Cell] = {}
    for c in cells:
        if c.status in ("PASS", "REFUSED"):
            continue
        if c.is_control and not include_controls:
            continue
        if c.is_control and c.method != "split_abs":
            continue
        mech = _mechanism(c)
        key = (c.row, mech, _raise_kind(c) if mech == "raises" else "")
        cur = best.get(key)
        if cur is None or rank(c) < rank(cur):
            best[key] = c
    out: list[tuple[Cell, str]] = []
    seen: dict[tuple[str, str], int] = {}
    for (row, mech, _), c in sorted(best.items()):
        i = seen[(row, mech)] = seen.get((row, mech), 0) + 1
        out.append((c, mech if i == 1 else f"{mech}-{i}"))
    return out


def write_repros(
    run_dir: str | Path,
    verify: bool = False,
    out_dir: str | Path | None = None,
    include_controls: bool = True,
    timeout: float = 900.0,
) -> list[Repro]:
    run = Path(run_dir)
    out = Path(out_dir) if out_dir else run / "repros"
    out.mkdir(parents=True, exist_ok=True)
    meta = json.loads((run / "run.json").read_text(encoding="utf-8"))
    cells = build_cells(study_records(run)[0])
    adjust(cells, float(meta["study"]["fwer"]), float(meta["study"]["fdr"]))
    results: list[Repro] = []
    skipped: list[str] = []
    for cell, mech in clusters(cells, include_controls):
        snippet = _snippet(cell)
        if snippet is None:
            skipped.append(f"{cell.row} ({mech}): no template")
            continue
        name = f"{cell.row.replace('/', '__').replace('=', '-')}__{mech}.py"
        path = out / name
        path.write_text(_script(cell, mech, snippet), encoding="utf-8", newline="\n")
        title = f"{cell.row} {mech}: {cell.status} at {cell.dgp} n={cell.n} alpha={cell.alpha}"
        results.append(Repro(title, path, cell.row, mech))
    if verify:
        for r in results:
            try:
                proc = subprocess.run(
                    [sys.executable, str(r.path)],
                    capture_output=True,
                    text=True,
                    timeout=timeout,
                    check=False,
                )
                r.exit_code = proc.returncode
                r.path.with_suffix(".out.txt").write_text(
                    proc.stdout + proc.stderr[-3000:], encoding="utf-8"
                )
            except subprocess.TimeoutExpired:
                r.exit_code = -1
    index = {
        "repros": [
            {"title": r.title, "file": r.path.name, "row": r.row, "kind": r.kind,
             "exit_code": r.exit_code}
            for r in results
        ],
        "skipped": skipped,
    }  # fmt: skip
    (out / "index.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    return results
