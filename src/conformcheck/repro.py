class FixedClassifier(ClassifierMixin, BaseEstimator):
    """Fixed linear-softmax classifier over 4 classes, temperature 2."""

    W = np.array([[2.0, -1.0, 0.5, -1.5], [-1.0, 2.0, 0.5, -0.5]])

    def __init__(self):
        self.classes_ = np.arange(4)
        self.n_features_in_ = 2
        self.is_fitted_ = True

